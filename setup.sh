    echo "[!] Node.js не найден! Установите Node.js 18+ с https://nodejs.org/"
    exit 1
fi

echo "[✓] Node.js обнаружен."
echo "Установка локального движка Lighthouse для 100% автономной работы..."
npm install
echo ""
echo "========================================================"
echo "  [✓] Все компоненты успешно настроены!"
echo "  Теперь запустите ./run.sh для начала аудита."
echo "========================================================"
